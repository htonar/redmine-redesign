import { describe, expect, it } from "vitest";
import { escapeCsvCell, toCsv } from "@/lib/csv";

describe("escapeCsvCell", () => {
  it("не трогает обычное значение", () => {
    expect(escapeCsvCell("Баг")).toBe("Баг");
  });

  it("оборачивает в кавычки значение с запятой", () => {
    expect(escapeCsvCell("Новая, в работе")).toBe('"Новая, в работе"');
  });

  it("дублирует кавычки и оборачивает значение с кавычкой", () => {
    expect(escapeCsvCell('Задача "срочная"')).toBe('"Задача ""срочная"""');
  });

  it("оборачивает в кавычки значение с переводом строки", () => {
    expect(escapeCsvCell("строка1\nстрока2")).toBe('"строка1\nстрока2"');
  });

  it("пустая строка остается пустой", () => {
    expect(escapeCsvCell("")).toBe("");
  });
});

describe("toCsv", () => {
  it("пустой список строк -> только заголовок", () => {
    expect(toCsv(["Показатель", "Значение"], [])).toBe("Показатель,Значение");
  });

  it("собирает заголовок и строки через \\r\\n", () => {
    const csv = toCsv(
      ["Показатель", "Значение"],
      [
        ["Всего задач", 42],
        ["Открыто", 30],
      ],
    );
    expect(csv).toBe("Показатель,Значение\r\nВсего задач,42\r\nОткрыто,30");
  });

  it("экранирует ячейки со спецсимволами внутри строк", () => {
    const csv = toCsv(["Комментарий"], [["привет, мир"]]);
    expect(csv).toBe('Комментарий\r\n"привет, мир"');
  });

  it("числовые значения приводит к строке без экранирования", () => {
    const csv = toCsv(["Часы"], [[1.5]]);
    expect(csv).toBe("Часы\r\n1.5");
  });
});
